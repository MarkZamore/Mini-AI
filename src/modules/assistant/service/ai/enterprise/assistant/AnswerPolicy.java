package ai.enterprise.assistant;

import java.util.Locale;

/** Routes local normative questions conservatively; it does not grade semantic entailment. */
final class AnswerPolicy {
    static final String INSUFFICIENT = "В текущей базе не найдены фрагменты, подтверждающие запрошенные нормы. "
        + "Уточните документ, организацию или нужную редакцию либо добавьте источник. "
        + "Без такого основания нельзя достоверно назвать обязательные условия, сроки и исключения.";
    static final String WEAK_EVIDENCE = "Найденные фрагменты не дают достаточного основания для ответа на этот вопрос. "
        + "Уточните название документа, категорию участников или ситуацию. "
        + "Для полного ответа нужны относящиеся к ней условия, сроки и исключения; общую практику нельзя выдавать за требования документов.";
    static final String CLARIFY = "Чтобы определить применимое правило, уточните документ, категорию участников или конкретную ситуацию. "
        + "Найденные положения могут относиться к другой области применения. Без уточнения нельзя достоверно перечислить все нужные условия и исключения.";
    static final String UNVERIFIED_RESPONSE = "По найденным фрагментам не удалось сформировать ответ с проверяемыми ссылками. "
        + "Откройте источники ниже или уточните документ и конкретный вопрос. "
        + "Полнота необходимых условий, сроков и исключений пока не установлена.";

    private AnswerPolicy() {}

    static boolean normative(String query) {
        String text=query.toLowerCase(Locale.ROOT);
        boolean local=text.matches("(?s).*(?:в (?:нашей|этой|данной) организации|у нас|нашего университета|в базе|по документам|в (?:этом |данном |указанном )?документе|құжатында|according to (?:the )?document|согласно|установлен|предусмотрен|обязател|редакци).*" );
        boolean general=text.matches("(?s).*(?:обычно|в целом|в общем|общие принципы|общие правила|общую практику|типичн|general advice|generally|жалпы).*" );
        general=general||text.matches("(?s).*(?:что такое|что означает|объясни термин|зачем нуж|what is|what does .* mean).*" );
        if(general&&!local) return false;
        return local||text.matches("(?s).*(?:норматив|регламент|услови|требован|критери|правил|порядок|процедур|обязан|срок|исключени|организаци|университет|колледж|институт|политик|противодейств|управлени[ея] рисками|шарт|талап|ереже|тәртіп|мерзім|requirements?|eligibility|regulation|deadlines?).*");
    }
}
